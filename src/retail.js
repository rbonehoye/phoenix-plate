// Retail spots at Elon. Unlike the dining halls these menus rarely change,
// so the data lives here instead of being fetched daily.
//
// Each item's `basis` says where its numbers come from:
//   official  - calories and macros from the restaurant's published nutrition guide
//   label     - from the product's package nutrition label
//   menu      - calories printed on Elon Dining's menu; protein/carbs/fat estimated
//   estimate  - all values estimated from similar items (no published nutrition)
//
// Rows: [name, calories, protein, carbs, fat, fiber, sugar, sodium(mg), serving]

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-');

function section(spotId, name, basis, rows) {
  return {
    name,
    items: rows.map(([n, calories, protein, carbs, fat, fiber = null, sugar = null, sodium = null, serving = null]) => ({
      id: `${spotId}-${slug(name)}-${slug(n)}`,
      name: n,
      calories,
      protein,
      carbs,
      fat,
      fiber,
      sugar,
      sodium,
      serving,
      basis,
      tags: [],
      allergens: [],
    })),
  };
}

